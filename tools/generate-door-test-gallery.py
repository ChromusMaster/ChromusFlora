from __future__ import annotations
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
RES=ROOT/'flora/src/main/resources'
CATALOG=json.loads((RES/'chromusflora/catalog.json').read_text())
SPECIES=[t['id'] for t in CATALOG['trees']]
FUNC_DIR=RES/'data/chromusflora/function/test'
DOC=ROOT/'docs/DOOR_TRAPDOOR_TEST_INDEX.md'
COLS=9
DX=4
DZ=4

lines=[
    '# Chromus Flora door + trapdoor visual test gallery',
    '# Run in a flat/open test area: /function chromusflora:test/doors_trapdoors',
    '# Gallery extends east (+X) and south (+Z) from the execution position.',
    'tellraw @s {"text":"Chromus Flora: generating 83 door/trapdoor pairs east/south of your position.","color":"green"}',
]
clear=[
    '# Clears the exact gallery footprint generated by doors_trapdoors.mcfunction.',
    'fill ~0 ~0 ~0 ~34 ~3 ~36 minecraft:air',
    'tellraw @s {"text":"Chromus Flora door/trapdoor gallery cleared.","color":"yellow"}',
]
md=['# Door + Trapdoor in-game test index','',
    'Run ` /function chromusflora:test/doors_trapdoors ` (without spaces around the command) in a flat/open test area.',
    '', 'The gallery grows toward **+X (east)** and **+Z (south)** from the position where the function is executed.',
    '', '| # | Row | Col | Species | Door | Trapdoor |', '|---:|---:|---:|---|---|---|']
for i,name in enumerate(SPECIES):
    row=i//COLS
    col=i%COLS
    x=col*DX
    z=row*DZ
    lines.append(f'# {i+1:02d} row={row+1} col={col+1} {name}')
    
    lines.append(f'setblock ~{x} ~0 ~{z} chromusflora:{name}_planks')
    lines.append(f'setblock ~{x+2} ~0 ~{z} chromusflora:{name}_planks')
    
    lower=f'chromusflora:{name}_door[facing=north,half=lower,hinge=left,open=false,powered=false]'
    upper=f'chromusflora:{name}_door[facing=north,half=upper,hinge=left,open=false,powered=false]'
    lines.append(f'setblock ~{x} ~1 ~{z} {lower}')
    lines.append(f'setblock ~{x} ~2 ~{z} {upper}')
    lines.append(f'setblock ~{x} ~1 ~{z} {lower}')
    trap=f'chromusflora:{name}_trapdoor[facing=north,half=bottom,open=true,powered=false,waterlogged=false]'
    lines.append(f'setblock ~{x+2} ~1 ~{z} {trap}')
    md.append(f'| {i+1} | {row+1} | {col+1} | `{name}` | `chromusflora:{name}_door` | `chromusflora:{name}_trapdoor` |')
lines.append('tellraw @s {"text":"Gallery ready. Doors are closed; trapdoors are open/vertical for front-face inspection.","color":"aqua"}')
FUNC_DIR.mkdir(parents=True,exist_ok=True)
(FUNC_DIR/'doors_trapdoors.mcfunction').write_text('\n'.join(lines)+'\n',encoding='utf-8')
(FUNC_DIR/'clear_doors_trapdoors.mcfunction').write_text('\n'.join(clear)+'\n',encoding='utf-8')
DOC.write_text('\n'.join(md)+'\n',encoding='utf-8')
print(json.dumps({'status':'PASS','species':len(SPECIES),'gallery':str((FUNC_DIR/'doors_trapdoors.mcfunction').relative_to(ROOT)), 'index':str(DOC.relative_to(ROOT))},indent=2))
